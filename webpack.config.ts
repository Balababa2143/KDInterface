import * as fs from 'fs'
import * as path from 'path'
import {ZipArchive, Archiver} from 'archiver'
import webpack from 'webpack'

const EntryFile = 'Generated/index.ts'
const BundleDir = 'Bundle'
const ArchiveFile = 'Deploy/kd-structured.zip'
/** Declarations emitted by ts-loader through Generated/tsconfig.json. */
const TypeFolder = 'Generated/@type'
/** npm shaped types package, staged outside the mod archive. */
const TypeBundleDir = 'Deploy/types'
const TypeArchiveFile = 'Deploy/kd-structured-types.zip'
/** package.json / tsconfig.json published alongside the declarations. */
const PackageAssetFolder = 'PackageAsset'
const AssetFolders: string[] = [
    'ModAsset'
]

async function CopyAssets() {
    await Promise.all(
        AssetFolders.map(
            assetFolder =>
                fs.promises.cp(assetFolder, BundleDir, { recursive: true })
        )
    )
}

/**
 * Stages the declarations next to the package manifest, so that unpacking the
 * types archive yields something `node_modules/kd-structured` can accept as is.
 * The mod archive keeps scripts and assets only, which is what keeps the mod
 * load fast.
 */
async function CopyTypes() {
    if (fs.existsSync(TypeBundleDir)) {
        await fs.promises.rm(TypeBundleDir, { recursive: true })
    }
    await fs.promises.mkdir(TypeBundleDir, { recursive: true })
    if (fs.existsSync(TypeFolder)) {
        await fs.promises.cp(TypeFolder, path.join(TypeBundleDir, '@type'), { recursive: true })
    }
    await fs.promises.cp(PackageAssetFolder, TypeBundleDir, { recursive: true })
}

function SetArchiverEventHandlers(writeStream: fs.WriteStream, archiver: Archiver) {
    writeStream.on('close', function () {
        console.log(archiver.pointer() + ' total bytes');
        console.log('archiver has been finalized and the output file descriptor has closed.');
    })
    writeStream.on('end', function () {
        console.log('Data has been drained');
    })
    archiver.on('warning', function (err) {
        if (err.code === 'ENOENT') {
            // log warning
        } else {
            // throw error
            throw err;
        }
    })
    archiver.on('error', function (err) {
        throw err;
    })
}

/**
 * execute build
 * @param {string} sourceDir folder whose contents become the archive root
 * @param {string} archiveFile target archive path
 */
async function BuildArchive(sourceDir: string, archiveFile: string) {
    const archiveFilePath = path.resolve(archiveFile)
    const stream = fs.createWriteStream(archiveFilePath)

    const zipArchiver = new ZipArchive({
        zlib: {
            level: 9
        }
    })
    SetArchiverEventHandlers(stream, zipArchiver)
    // pipe archive data to the file
    zipArchiver.pipe(stream)
    await zipArchiver
        .directory(sourceDir, false)
        .finalize()
    await new Promise<void>(resolve => stream.on("close", resolve))
}

function PreBuild(): webpack.WebpackPluginInstance {
    return {
        apply: (compiler) => {
            compiler.hooks.beforeCompile.tapPromise('DoneArchiveBuilding', async (_) => {
                const archiveDir = path.dirname(path.resolve(ArchiveFile))
                if (!fs.existsSync(archiveDir)) {
                    fs.mkdirSync(archiveDir, { recursive: true })
                }

                const stalePaths = [
                    ArchiveFile,
                    TypeArchiveFile,
                    // Regenerated by ts-loader during this very compile.
                    TypeFolder,
                    // Written by builds that still shipped the declarations inside the mod archive.
                    path.join(BundleDir, '@type'),
                ]
                for (const stalePath of stalePaths) {
                    if (fs.existsSync(stalePath)) {
                        fs.rmSync(stalePath, { recursive: true })
                    }
                }
            })
        }
    }
}

function PostBuild(): webpack.WebpackPluginInstance {
    return {
        apply: (compiler) => {
            compiler.hooks.done.tapPromise('DoneArchiveBuilding', async (stats) => {
                if (!stats.hasErrors()) {
                    await CopyAssets()
                    await CopyTypes()
                    await BuildArchive(BundleDir, ArchiveFile)
                    await BuildArchive(TypeBundleDir, TypeArchiveFile)
                }
            })
        }
    }
}

function Config(env: Record<string, unknown>, argv: Record<string, string>): webpack.Configuration {

    return {
        entry: path.resolve(EntryFile),
        output: {
            path: path.join(path.resolve(BundleDir), 'kd-structured'),
            filename: 'bundle.es',
            module: true,
            library: {
                // name: 'kd-structured',
                type: 'module'
            },
            clean: true
        },
        externalsType: 'var',
        externals: {
            "pixi-filters": "PIXI",
            "pixi.js": "PIXI",
            "pixi.js-legacy": "PIXI"
        },
        module: {
            rules: [
                {
                    test: /\.ts?$/,
                    use: {
                        // ts-loader finds Generated/tsconfig.json via its default config discovery from the entry folder.
                        'loader': 'ts-loader',
                    },
                    exclude: /node_modules/,
                },
            ],
        },
        resolve: {
            extensions: ['.tsx', '.ts', '.js'],
        },
        devtool: (argv['mode'] === 'production') ? false : 'inline-source-map',
        plugins: [
            PreBuild(),
            PostBuild()
        ]
    }
}

export default Config
